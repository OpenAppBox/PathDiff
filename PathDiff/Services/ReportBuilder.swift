import Foundation

nonisolated enum ReportFormat: String, Sendable, CaseIterable {
    case markdown
    case csv

    var fileExtension: String { self == .markdown ? "md" : "csv" }
    var title: String { self == .markdown ? "Markdown" : "CSV" }
}

/// One line of a comparison report.
nonisolated struct ReportItem: Sendable {
    let kind: ChangeKind
    let path: String
    /// For moves: the path on the right side.
    let counterpartPath: String?
    let isDirectory: Bool
    /// Files contained in a one-sided or moved folder.
    let fileCount: Int
    let isExactMove: Bool
    let leftSize: Int64?
    let rightSize: Int64?
}

nonisolated struct ReportData: Sendable {
    let leftRoot: String
    let rightRoot: String
    let generated: Date
    let summary: DiffSummary
    let options: DiffOptions
    let respectsGitIgnore: Bool
    let items: [ReportItem]
}

/// Renders the full list of differences (ignoring sidebar filters) for sharing.
nonisolated enum ReportBuilder {
    static func render(_ data: ReportData, format: ReportFormat) -> String {
        switch format {
        case .markdown: markdown(data)
        case .csv: csv(data)
        }
    }

    static func title(for kind: ChangeKind) -> String {
        switch kind {
        case .modified: "Modified"
        case .moved: "Moved or renamed"
        case .leftOnly: "Only in left (missing from right)"
        case .rightOnly: "Only in right (extra in right)"
        }
    }

    private static func markdown(_ data: ReportData) -> String {
        var lines: [String] = []
        lines.append("# Folder comparison")
        lines.append("")
        lines.append("| | |")
        lines.append("| --- | --- |")
        lines.append("| Left | `\(data.leftRoot)` |")
        lines.append("| Right | `\(data.rightRoot)` |")
        lines.append("| Generated | \(data.generated.formatted(date: .abbreviated, time: .shortened)) |")
        var options: [String] = []
        if data.respectsGitIgnore { options.append(".gitignore respected") }
        if data.options.ignoreWhitespace { options.append("whitespace ignored") }
        if data.options.ignoreLineEndings { options.append("line endings ignored") }
        if data.options.comparisonMethod == .quick { options.append("quick comparison (size and date)") }
        lines.append("| Options | \(options.isEmpty ? "—" : options.joined(separator: ", ")) |")
        lines.append("")
        let summary = data.summary
        func total(_ kind: ChangeKind, _ label: String) -> String {
            let count = summary.count(of: kind)
            let bytes = summary.bytes(of: kind)
            return "**\(count)** \(label)" + (count > 0 && bytes > 0 ? " (\(ByteCountFormatter.string(fromByteCount: bytes, countStyle: .file)))" : "")
        }
        lines.append([
            total(.modified, "modified"), total(.moved, "moved"), total(.leftOnly, "only in left"), total(.rightOnly, "only in right"),
            "\(summary.identical) identical", "\(summary.ignored) ignored",
        ].joined(separator: " · "))

        for kind in ChangeKind.allCases {
            let items = data.items.filter { $0.kind == kind }
            guard !items.isEmpty else { continue }
            lines.append("")
            lines.append("## \(title(for: kind)) (\(items.count))")
            lines.append("")
            for item in items {
                var line = "- `\(item.path)\(item.isDirectory ? "/" : "")`"
                if let counterpart = item.counterpartPath {
                    line += " → `\(counterpart)\(item.isDirectory ? "/" : "")`"
                    if !item.isExactMove { line += " (edited)" }
                }
                if item.isDirectory { line += " — \(item.fileCount) file\(item.fileCount == 1 ? "" : "s")" }
                lines.append(line)
            }
        }
        lines.append("")
        lines.append("---")
        lines.append("")
        lines.append("_Generated by PathDiff · An OpenAppBox App · [\(OpenAppBox.websiteLabel)](\(OpenAppBox.website.absoluteString))_")
        lines.append("")
        return lines.joined(separator: "\n")
    }

    private static func csv(_ data: ReportData) -> String {
        var lines = ["change,path,counterpart_path,is_folder,file_count,left_size,right_size"]
        for item in data.items {
            let fields = [
                item.kind.rawValue,
                item.path,
                item.counterpartPath ?? "",
                item.isDirectory ? "true" : "false",
                String(item.fileCount),
                item.leftSize.map(String.init) ?? "",
                item.rightSize.map(String.init) ?? "",
            ]
            lines.append(fields.map(escape).joined(separator: ","))
        }
        return lines.joined(separator: "\n") + "\n"
    }

    private static func escape(_ field: String) -> String {
        guard field.contains(where: { $0 == "," || $0 == "\"" || $0 == "\n" }) else { return field }
        return "\"" + field.replacingOccurrences(of: "\"", with: "\"\"") + "\""
    }
}
